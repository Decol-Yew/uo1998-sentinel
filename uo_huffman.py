# (bit長, コード値) -> シンボル のルックアップを構築 (UOコードは prefix-free)
_LOOKUP = {(c, v): i for i, (c, v) in enumerate(HUFFMAN)}


class HuffmanDecompressor:
    """連続ストリーム対応の解凍器。chunk を順に feed して解凍バイト列を得る。

    UO仕様: 圧縮側は終端コード(symbol 256, 4bit=0x0D)を出した後、バイト境界まで
    ゼロパディングする。よって解凍側は終端に当たったら現在バイトの残りビットを
    捨てて次のバイト境界へ再整列する。コードがchunk境界をまたぐ場合に備え、
    未確定のビット列は内部バッファに保持して次のfeedへ繰り越す。
    """

    def __init__(self):
        self._pending = bytearray()  # 未消費バイト
        self._bit = 0                # _pending[0] 内のビット位置(0..7, MSB始まり)

    def feed(self, data: bytes) -> bytes:
        buf = self._pending
        buf += data
        out = bytearray()
        n = len(buf)
        byte_i = 0
        bit = self._bit
        code_start_byte = 0
        code_start_bit = bit
        cur_len = 0
        cur_val = 0
        while byte_i < n:
            b = (buf[byte_i] >> (7 - bit)) & 1
            cur_val = (cur_val << 1) | b
            cur_len += 1
            bit += 1
            if bit == 8:
                bit = 0
                byte_i += 1
            sym = _LOOKUP.get((cur_len, cur_val))
            if sym is not None:
                if sym < 256:
                    out.append(sym)
                else:
                    # 終端: 現バイトの残りビット(ゼロパディング)を捨ててバイト境界へ
                    if bit != 0:
                        bit = 0
                        byte_i += 1
                cur_len = 0
                cur_val = 0
                code_start_byte = byte_i
                code_start_bit = bit
            elif cur_len > 11:
                raise ValueError("huffman desync (code length > 11)")
        # コード途中でデータ切れ → code_start まで巻き戻して次回へ繰り越し
        self._pending = bytearray(buf[code_start_byte:])
        self._bit = code_start_bit
        return bytes(out)


def decompress(data: bytes) -> bytes:
    return HuffmanDecompressor().feed(data)
